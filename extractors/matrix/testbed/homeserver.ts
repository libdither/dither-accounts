/**
 * The testbed's homeserver, as a library: continuwuity's config (the one testbed.ts writes), and a throwaway server
 * for a test (test/chat-parity/matrix-oracle.test.ts) on a fresh directory and a port the kernel picked, with users
 * registered by token as the testbed registers its own.
 */
import { readdirSync, readFileSync, readlinkSync } from 'node:fs';
import { join } from 'node:path';
import { MatrixClient, MatrixError } from '../src/http.ts';

export const SERVER_NAME = 'dither.test';

/** continuwuity's config: federation off, registration by token only, no first-run admin flow. */
export function continuwuityConfig(o: { dbDir: string; host: string; port: number; registrationToken: string }): string {
  return `# Generated by extractors/matrix/testbed; rewritten on every start.
[global]
server_name = "${SERVER_NAME}"
database_path = "${o.dbDir}"
address = ["${o.host}"]
port = ${o.port}
allow_federation = false
allow_registration = true
registration_token = "${o.registrationToken}"
# No first-run admin flow: no admin room in the test users' sidebars.
force_disable_first_run_mode = true
allow_encryption = true
trusted_servers = []
allow_announcements_check = false
new_user_displayname_suffix = ""
log = "info"
`;
}

/** The TCP port a process listens on, from /proc: continuwuity given port 0 logs "0", not the port it got. */
function listeningPort(pid: number): number | null {
  const inodes = new Set<string>();
  for (const fd of readdirSync(`/proc/${pid}/fd`)) {
    try {
      const m = readlinkSync(`/proc/${pid}/fd/${fd}`).match(/^socket:\[(\d+)\]$/);
      if (m) inodes.add(m[1]!);
    } catch {}
  }
  for (const line of readFileSync(`/proc/${pid}/net/tcp`, 'utf8').split('\n').slice(1)) {
    const f = line.trim().split(/\s+/);
    // local_address, state 0A (LISTEN), inode
    if (f[3] === '0A' && inodes.has(f[9]!)) return parseInt(f[1]!.split(':')[1]!, 16);
  }
  return null;
}

export interface Homeserver {
  baseUrl: string;
  registrationToken: string;
  /** Everything it logged, for a failing test to show. */
  log: string[];
  stop(): Promise<void>;
}

/**
 * A continuwuity on 127.0.0.1, on a port the kernel picks, its database in `dir`. Ready when it says it is listening
 * (its own log line), with no polling; fails if it exits first.
 */
export async function startHomeserver(o: { bin: string; dir: string }): Promise<Homeserver> {
  const registrationToken = crypto.randomUUID();
  const config = join(o.dir, 'continuwuity.toml');
  await Bun.write(config, continuwuityConfig({ dbDir: join(o.dir, 'db'), host: '127.0.0.1', port: 0, registrationToken }));
  const proc = Bun.spawn([o.bin, '-c', config], { cwd: o.dir, stdout: 'pipe', stderr: 'pipe', env: { ...process.env, NO_COLOR: '1' } });
  const log: string[] = [];
  let listening: () => void;
  const ready = new Promise<void>((r) => (listening = r));
  const read = async (s: ReadableStream<Uint8Array>) => {
    let buf = '';
    for await (const chunk of s) {
      buf += new TextDecoder().decode(chunk);
      let nl: number;
      while ((nl = buf.indexOf('\n')) >= 0) {
        const line = buf.slice(0, nl).replace(/\x1b\[[0-9;]*m/g, '');
        buf = buf.slice(nl + 1);
        log.push(line);
        if (/Listening on /.test(line)) listening();
      }
    }
  };
  void read(proc.stdout);
  void read(proc.stderr);
  const exited = proc.exited.then((code) => {
    throw new Error(`continuwuity exited (${code}) before it listened:\n${log.slice(-20).join('\n')}`);
  });
  await Promise.race([ready, exited]);
  exited.catch(() => {});
  const port = listeningPort(proc.pid);
  if (!port) throw new Error('continuwuity says it listens, but on no TCP port this process holds');
  return {
    baseUrl: `http://127.0.0.1:${port}`,
    registrationToken,
    log,
    async stop() {
      proc.kill('SIGTERM');
      await proc.exited;
    },
  };
}

/** A user registered with the token (the two-step register a client does), signed in. */
export async function registerUser(hs: Pick<Homeserver, 'baseUrl' | 'registrationToken'>, username: string, password: string): Promise<MatrixClient> {
  const c = new MatrixClient(hs.baseUrl);
  const body = { username, password, initial_device_display_name: 'testbed' };
  let session: string | undefined;
  try {
    await c.request('POST', '/_matrix/client/v3/register', { auth: false, retries: 0, body });
  } catch (e) {
    if (!(e instanceof MatrixError) || e.status !== 401) throw e;
    session = e.data.session;
  }
  const res = await c.request('POST', '/_matrix/client/v3/register', { auth: false, retries: 0, body: { ...body, auth: { type: 'm.login.registration_token', token: hs.registrationToken, session } } });
  c.accessToken = res.access_token;
  return c;
}
